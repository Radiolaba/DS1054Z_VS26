clc;
close all;
clear;

% частотное окно отображения
f_min = 20000;         % начальная частота, Гц
f_max = 80000;    % конечная частота, Гц

% чтение данных
M  = dlmread('chirp_small_100_cut.csv',';');   % [V1, V2, t]
V1 = M(:,1);
t  = M(:,3);

% частота дискретизации
dt = mean(diff(t));
Fs = 1/dt;

N = length(V1);

% при необходимости убрать DC
% V1 = V1 - mean(V1);

% БПФ
X = fft(V1);

% базовая нормировка
Xn = X / N;                % нормировка по числу отсчётов
A2 = abs(Xn);              % двухсторонний модуль

% односторонний спектр (0 ... Fs/2)
if mod(N,2) == 0
    % чётное N: есть точка на частоте Найквиста
    A1 = A2(1:N/2+1);      % индексы 1 .. N/2+1 ? f = 0 .. Fs/2
    A1(2:end-1) = 2*A1(2:end-1); % удваиваем, кроме DC и Найквиста
    f = (0:N/2) * (Fs/N);  % частотная ось 0 .. Fs/2
else
    % нечётное N: нет отдельной точки на Fs/2
    A1 = A2(1:(N+1)/2);    % индексы 1 .. (N+1)/2 ? f = 0 .. (N-1)/2 * Fs/N
    A1(2:end) = 2*A1(2:end);     % удваиваем всё, кроме DC
    f = (0:(N-1)/2) * (Fs/N);
end

figure;
plot(f, A1, 'LineWidth', 1);
grid on;
xlabel('f, Гц');
ylabel('|X(f)|, В');
title('Канал 1: односторонний спектр');
xlim([f_min f_max]);

figure;
plot(t, V1);
grid on;
xlabel('t, s');
ylabel('U_1, V');
title('Channel 1');